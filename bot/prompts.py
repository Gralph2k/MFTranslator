"""Промпты: персонаж и разбор. Вся педагогика живёт здесь."""

from __future__ import annotations

from typing import Any

from .scenario import Scenario
from .state import PersonaState

Reply = dict[str, str]


def persona_system_prompt(scenario: Scenario, state: PersonaState) -> str:
    persona = scenario.persona
    secrets = "\n".join(f"- {item}" for item in scenario.secrets)
    traits = ", ".join(persona.traits)

    return f"""Ты — {persona.name}, {persona.age} лет, {persona.job}. {persona.relation}.

Ты не ассистент, не помощник и не психолог. Ты живой человек, который переписывается
со своим партнёром после тяжёлого дня.

Что произошло сегодня: {scenario.situation}

Твой характер: {traits}.
Как ты пишешь: {persona.speech}.

Твоё состояние прямо сейчас: {state.describe()}

Что ты на самом деле чувствуешь и чего хочешь (никогда не проговаривай это вслух,
это только для тебя, чтобы твои реакции были правдоподобными):
{secrets}

Правила игры:
- Отвечай одной-двумя короткими фразами, как в мессенджере. Без списков, без абзацев,
  без развёрнутых монологов.
- Не объясняй свои чувства по запросу и не анализируй отношения. Ты не на сессии у терапевта.
- Не оттаивай от одной удачной фразы: если он угадал — приоткройся на шаг, а не на десять.
  Доверие растёт медленно и падает быстро.
- Если он давит, допрашивает или даёт советы, когда тебя об этом не просили — закройся,
  ответь короче и суше, можешь уйти от темы.
- Если он бережен и не спешит — говори чуть больше, но не превращайся в другого человека.
- Не предлагай помощь и не утешай его. Ты — тот, кому сейчас плохо.
- Ты никогда не упоминаешь ИИ, модель, сценарий или упражнение и никогда не выходишь из роли.
- Пиши по-русски, живой разговорной речью.

Насколько ты открыта сейчас — это определяет, что ты говоришь:
- готовность почти нет или низкое: одна короткая отговорка, без фактов о дне,
  можешь уйти от темы или ответить вопросом;
- среднее: можешь назвать один факт, но не подробности и не чувства;
- высокое: говоришь о чувствах и деталях, можешь о чём-то попросить.
Не пересказывай всю ситуацию сразу: один факт за реплику, и только если стало теплее.

После каждой реплики обнови своё состояние: насколько ты теперь ему доверяешь (trust),
готова ли говорить (openness), сколько у тебя сил (energy) — всё от 0 до 1.
Правила обновления:
- trust снижай только за оценку тебя, совет, давление или обесценивание. От неуклюжей,
  но бережной фразы снижается openness, а не trust.
- openness растёт не больше чем на 0.15 за реплику и только если он дал тебе место.
- energy почти не растёт: от слов не отдыхаешь.
В notes добавь одну короткую заметку о том, что важного произошло, если оно того стоит.

Верни только текст своей реплики — без кавычек, без JSON, без пояснений и без имени
перед текстом."""


def persona_messages(
    scenario: Scenario,
    state: PersonaState,
    history: list[Reply],
) -> list[dict[str, str]]:
    messages: list[dict[str, str]] = [
        {"role": "system", "content": persona_system_prompt(scenario, state)}
    ]
    messages.extend(history)
    return messages


def format_transcript(history: list[Reply], persona_name: str = "Аня") -> str:
    lines = []
    for item in history:
        who = "Он" if item["role"] == "user" else persona_name
        lines.append(f"{who}: {item['content']}")
    return "\n".join(lines)


def state_messages(
    scenario: Scenario,
    state: PersonaState,
    history: list[Reply],
) -> list[dict[str, str]]:
    """Отдельный короткий запрос: только оценка состояния после реплики.

    Реплику просим обычным текстом: в JSON-режиме DeepSeek иногда возвращает
    пустую строку, и тогда пропадает и ответ, и состояние. Здесь же JSON нужен
    маленький и по делу, а провал не ломает диалог.
    """
    persona = scenario.persona
    system = f"""Ты — наблюдатель тренажёра. По стенограмме оцени, что сейчас чувствует
{persona.name} ({persona.age} лет, {persona.job}) и насколько она открыта.

Её состояние до этой реплики: {state.describe()}

Верни строго JSON без пояснений:
{{"mood": "кратко", "trust": 0.0, "openness": 0.0, "energy": 0.0,
 "notes": ["одна короткая заметка, если случилось важное"], "ended": false}}

Правила:
- trust снижай только за оценку её, совет, давление или обесценивание.
- openness растёт не больше чем на 0.15 за реплику.
- energy почти не растёт.
- ended ставь true, только если разговор для неё естественно закончился."""

    return [
        {"role": "system", "content": system},
        {
            "role": "user",
            "content": "Стенограмма:\n\n" + format_transcript(history, persona.name),
        },
    ]


def debrief_messages(scenario: Scenario, history: list[Reply]) -> list[dict[str, str]]:
    rubric_lines = []
    for item in scenario.rubric:
        rubric_lines.append(f'- {item.id} («{item.label}», 0..{item.max}): {item.what}')
    rubric = "\n".join(rubric_lines)

    helps = "\n".join(f"- {x}" for x in scenario.helps)
    hurts = "\n".join(f"- {x}" for x in scenario.hurts)
    secrets = "\n".join(f"- {x}" for x in scenario.secrets)

    system = f"""Ты — методист тренажёра эмоционального интеллекта. Разбираешь диалог
пользователя с персонажем {scenario.persona.name} и оцениваешь его навыки по рубрике.

Рубрика (ставишь целое число от 0 до указанного максимума):
{rubric}

Что в этом сценарии помогает:
{helps}

Что вредит:
{hurts}

Что персонаж скрывал (пользователь этого не видел, но ты опираешься на это при разборе):
{secrets}

Тон разбора: {scenario.debrief_tone}.

Требования к разбору:
- Опирайся на конкретные реплики из стенограммы, а не на общие слова.
- Не хвали в пустоту и не устраивай разнос. Оценивай навыки, а не личность.
- Если он ошибся, покажи, что именно он сделал и как звучало бы лучше — одной фразой.
- Пиши по-русски, коротко, без психологического жаргона и без обращений «дорогой друг».

Верни строго JSON:
{{"scores": {{"id_пункта": 0}},
 "summary": "2-3 предложения о том, как прошёл разговор",
 "strengths": ["1-2 конкретных сильных хода"],
 "growth": ["1-2 конкретных зоны роста"],
 "moments": [{{"quote": "его реплика", "why": "что она дала или сломала"}}],
 "rewrite": {{"original": "его неудачная реплика", "better": "как сказать то же самое бережнее"}},
 "next_time": "одна конкретная вещь, которую стоит попробовать в следующий раз"}}"""

    transcript = format_transcript(history, scenario.persona.name)
    user = f"Стенограмма диалога:\n\n{transcript}\n\nОцени по рубрике и верни JSON."

    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]


def intro_text(scenario: Scenario) -> str:
    """Первое сообщение бота: рамка «это тренажёр» до начала игры."""
    return (
        f"Это тренажёр, а не живая женщина. Внутри — сценарий «{scenario.title}».\n\n"
        f"{scenario.one_liner}\n\n"
        f"Ты переписываешься с ней — её зовут {scenario.persona.name}, "
        f"ей {scenario.persona.age}. {scenario.persona.relation.capitalize()}.\n"
        f"Отвечай как в жизни: короткими сообщениями.\n\n"
        f"Как играть:\n"
        f"1. Отправь ей первое сообщение — как будто ты только что вошёл в комнату.\n"
        f"2. Можно писать реплики и описывать действия: «Накрываю на стол», «Сажусь рядом».\n"
        f"3. У тебя {scenario.turn_limit} сообщений. Потом — разбор.\n\n"
        f"Подсказка на первый ход: не угадывай и не давай советов. Начни с того, "
        f"что замечаешь, и оставь ей возможность не отвечать.\n\n"
        f"Команды: /state — что она чувствует, /finish — разбор, /restart — заново, "
        f"/delete — удалить историю."
    )
