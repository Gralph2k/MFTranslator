def format_transcript(history: list[Reply], persona_name: str = "Аня") -> str:
    lines = []
    for item in history:
        who = "Он" if item["role"] == "user" else persona_name
        lines.append(f"{who}: {item['content']}")
    return "\n".join(lines)


def _player_question_facts(history: list[Reply]) -> str:
    """Объективные факты о вопросах игрока: методист не должен путать их с её вопросами."""
    player = [str(item.get("content", "")) for item in history if item.get("role") == "user"]
    heroine = [
        str(item.get("content", "")) for item in history if item.get("role") == "assistant"
    ]
    with_question = [message for message in player if "?" in message]
    two_plus = [message for message in player if message.count("?") >= 2]
    return (
        f"- реплик игрока: {len(player)}\n"
        f"- из них с вопросительным знаком: {len(with_question)}; "
        f"всего «?»: {sum(message.count('?') for message in player)}\n"
        f"- реплик с двумя и более вопросами: {len(two_plus)}\n"
        f"- «?» в репликах героини: {sum(message.count('?') for message in heroine)} "
        f"(игроку не засчитываются)"
    )


def state_messages(
    scenario: Scenario,
    state: PersonaState,
    history: list[Reply],
) -> list[dict[str, str]]:
    """Отдельный короткий запрос: только оценка состояния после реплики.

    Реплику просим обычным текстом: в JSON-режиме DeepSeek иногда возвращает
    пустую строку, и тогда пропадает и ответ, и состояние. Здесь же JSON нужен
    маленький и по делу, а провал не ломает диалог.
    """
    persona = scenario.persona
    red_flags = ""
    if scenario.red_flags:
        lines = "\n".join(f"- {item}" for item in scenario.red_flags)
        red_flags = f"""
- Для неё недопустимо (красные линии):
{lines}
  Если он перешёл красную линию и она закончила разговор, ended=true, а mood — что она
  почувствовала, когда решила уйти."""
    early = ""
    if scenario.is_correspondence and len(history) <= 6:
        early = """
- Это начало переписки: не снижай trust за банальное, неловкое или неловко
  сформулированное сообщение и не считай уход от светского вопроса давлением. Снижай
  только за агрессию, унижение, оценку её или навязчивость после «нет». Интерес может
  упасть, но не в ноль с первого раза: у него есть ещё ходы."""
    system = f"""Ты — наблюдатель тренажёра. По стенограмме оцени, что сейчас чувствует
{persona.name} ({persona.age} лет, {persona.job}) и насколько она открыта.

Её состояние до этой реплики: {state.describe()}
Числа до этой реплики: trust={state.trust:.2f}, openness={state.openness:.2f},
energy={state.energy:.2f}.

Верни строго JSON без пояснений:
{{"mood": "2–4 слова живым языком", "trust": 0.0, "openness": 0.0, "energy": 0.0,
 "notes": ["одна короткая заметка, если случилось важное"], "ended": false}}

Правила:
- mood — не диагноз, а живое описание: что в ней сейчас борется. Можно с противоречием:
  «обижена, но тянет к нему», «устала и злится», «теплеет, боится показать». Не пиши
  «больше не ждёт», «всё решила», «закрылась навсегда»: это решение, а не состояние,
  и оно тянет следующие реплики в приговор.
- notes — только её действие и что для неё это значило: «ответила коротко», «пошутила»,
  «спросила», «закрылась». Не пиши «он», «его», «ему» — заметка только о ней, без
  оценки его поступков и без счёта, какое это сообщение. Не превращай заметки в
  обвинительный список его промахов.
  Плохо: «он ответил шаблоном». Хорошо: «ответила коротко, без вложения».
- trust — это про надёжность и честность, а не про нежность. Тёплое слово не поднимает
  trust, если он ушёл от прямого вопроса по делу, не договаривает или обесценил её чувство.
  За уход от прямого вопроса по делу trust снижай. За то, что он развивает её тему вместо
  ответа на её проверочный вопрос, trust не снижай: она часто спрашивает не чтобы получить
  ответ, а чтобы посмотреть, как он обойдётся с её словами.
- trust снижай только за оценку её, совет, давление, обесценивание, ложь или уход
  от прямого вопроса по делу.
- trust растёт не больше чем на 0.1 за реплику: один тёплый ход не переписывает историю.
- openness растёт не больше чем на 0.15 за реплику.
- energy почти не растёт.
- ended ставь true, только если разговор для неё естественно закончился. Если она
  предупреждает, что ей скоро пора, но ещё продолжает отвечать, ended=false; ended=true
  ставь, только когда она попрощалась и действительно закончила.
- Если в её последней реплике ясное прощание или отказ продолжать («пока», «не пиши
  больше», «не наберу») — ended=true, даже если он после этого успел написать ещё
  одно сообщение. Не жди его ответа: она уже закончила.{early}{red_flags}"""

    return [
        {"role": "system", "content": system},
        {
            "role": "user",
            "content": "Стенограмма:\n\n" + format_transcript(history, persona.name),
        },
    ]


