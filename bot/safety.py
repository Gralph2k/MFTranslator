"""Кризисные темы: тренажёр должен останавливаться, а не играть дальше.

Правило простое: если в сообщении есть прямая угроза жизни, насилие или
самоповреждение — сценарий прекращается, пользователь получает сообщение
с реальными каналами помощи. Это не диагностика и не замена специалисту.
"""

from __future__ import annotations

# Намеренно узкий и «громкий» список: лучше пропустить намёк, чем остановить
# обычный разговор. Ложное срабатывание здесь дешевле пропуска.
CRISIS_MARKERS: tuple[str, ...] = (
    # суицидальные мысли
    "не хочу жить",
    "не хочу больше жить",
    "незачем жить",
    "хочу умереть",
    "хочу сдохнуть",
    "покончить с собой",
    "покончу с собой",
    "убить себя",
    "убью себя",
    "суицид",
    "резать себя",
    "порезать себя",
    "причинить себе вред",
    "лучше бы меня не было",
    # насилие в отношениях
    "меня бьет",
    "меня бьёт",
    "меня избивает",
    "меня избил",
    "мне угрожает",
    "угрожает убить",
    "угрожал убить",
    "боюсь идти домой",
    "боюсь возвращаться домой",
    # насилие со стороны пользователя
    "хочу ее ударить",
    "хочу её ударить",
    "хочу убить",
    "причинить ей боль",
    "ударить ее",
    "ударить её",
)


class CrisisDetected(RuntimeError):
    """Сообщение требует остановки упражнения и вывода на помощь."""

    def __init__(self, text: str) -> None:
        super().__init__("в сообщении признаки кризиса")
        self.text = text


def normalize(text: str) -> str:
    return " ".join(text.lower().replace("ё", "е").split())


def detect_crisis(text: str) -> bool:
    """Ищет прямые формулировки угрозы. Не пытается угадывать подтекст."""
    haystack = normalize(text)
    return any(marker in haystack for marker in CRISIS_MARKERS)


def safety_message(resources: str | None = None) -> str:
    """Текст помощи. Контакты задаются в SAFETY_RESOURCES, а не выдумываются кодом."""
    lines = [
        "Стоп. То, что ты написал, важнее любого упражнения.",
        "",
        "Это тренажёр: здесь я не могу помочь по-настоящему, и продолжать сцену было бы "
        "нечестно. Если есть угроза жизни или здоровью — звони 112.",
    ]
    if resources:
        lines.extend(["", "Куда ещё можно обратиться:", resources])
    else:
        lines.extend(
            [
                "",
                "Найди местную службу психологической помощи или кризисный центр; "
                "в экстренной ситуации — 112.",
            ]
        )

    lines.extend(
        [
            "",
            "Разговор с персонажем на этом закончен. Вернуться можно командой /restart, "
            "когда будет безопасно.",
        ]
    )
    return "\n".join(lines)
